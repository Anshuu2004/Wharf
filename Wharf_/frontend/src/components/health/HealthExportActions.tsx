import { Copy, Download, Check, Printer, Zap } from 'lucide-react';
import { useState } from 'react';
import { Button, Card } from '../ui';
import { useToast } from '../ui/useToast';

interface HealthData {
  score: number;
  breakdown: Record<string, number>;
  suggestions: string[];
  contributionScore?: number;
  contributionSuggestions?: string[];
}

interface HealthExportActionsProps {
  healthData: HealthData;
  repoUrl: string;
}

export const HealthExportActions = ({ healthData, repoUrl }: HealthExportActionsProps) => {
  const [copied, setCopied] = useState(false);
  const { showToast } = useToast();

  const generateReport = () => {
    const repoName = repoUrl.split('/').slice(-2).join('/');
    const date = new Date().toLocaleDateString('en-US', {
      year: 'numeric',
      month: 'long',
      day: 'numeric',
    });

    return `# 📊 Repository Health Report

**Repository:** ${repoName}
**Date:** ${date}
**Score:** ${healthData.score}/100

## 📈 Score Breakdown

${Object.entries(healthData.breakdown)
  .map(([key, value]) => `- **${key.charAt(0).toUpperCase() + key.slice(1)}:** ${value}/20`)
  .join('\n')}

## 💡 Suggestions

${healthData.suggestions.map((s: string) => `- ${s}`).join('\n')}

${healthData.contributionScore ? `## 🤝 Contribution Readiness\n\n**Score:** ${healthData.contributionScore}/100\n\n${healthData.contributionSuggestions?.map((s: string) => `- ${s}`).join('\n')}` : ''}

---
*Generated by Wharf - Repository Health Analysis Tool*`;
  };

  const handleCopy = async () => {
    const report = generateReport();
    await navigator.clipboard.writeText(report);
    setCopied(true);
    showToast('Report Copied To Clipboard!', 'success');
    setTimeout(() => setCopied(false), 2000);
  };

  const handleDownload = () => {
    const report = generateReport();
    const blob = new Blob([report], { type: 'text/markdown' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = `health-report-${new Date().toISOString().slice(0, 10)}.md`;
    a.click();
    URL.revokeObjectURL(url);
    showToast('Report Downloaded Successfully!', 'success');
  };

  const handlePrint = () => {
    const report = generateReport();
    const printWindow = window.open('', '_blank');
    if (printWindow) {
      printWindow.document.write(`
        <html>
          <head><title>Health Report</title></head>
          <body><pre>${report}</pre></body>
        </html>
      `);
      printWindow.document.close();
      printWindow.print();
    }
  };

  return (
    <Card variant="hard-sm" rounded="2xl" className="p-4">
      <div className="flex flex-wrap items-center justify-between gap-3">
        <div className="flex items-center gap-2">
          <div className="p-2 rounded-lg bg-wharf-green/10 border border-wharf-green-dark">
            <Zap className="w-5 h-5 text-wharf-green-darker" />
          </div>
          <div>
            <p className="font-mono text-sm font-bold text-wharf-text-primary">Export Report</p>
            <p className="font-mono text-[11px] text-wharf-text-secondary capitalize">
              Share or save your analysis
            </p>
          </div>
        </div>

        <div className="w-full sm:w-auto flex flex-wrap sm:flex-nowrap gap-3 items-center mt-2 sm:mt-0">
          <Button size="sm" variant="secondary" onClick={handleCopy} className="flex-[1] sm:flex-none min-w-[100px]">
            {copied ? (
              <>
                <Check className="w-4 h-4" />
                Copied!
              </>
            ) : (
              <>
                <Copy className="w-4 h-4" />
                Copy
              </>
            )}
          </Button>

          <Button size="sm" variant="secondary" onClick={handleDownload} className="flex-[1] sm:flex-none min-w-[100px]">
            <Download className="w-4 h-4" />
            Download
          </Button>

          <div className="w-full sm:w-auto flex justify-center">
            <Button size="sm" variant="outline" onClick={handlePrint} className="w-full sm:w-auto max-w-[200px]">
              <Printer className="w-4 h-4" />
              Print
            </Button>
          </div>
        </div>
      </div>
    </Card>
  );
};

